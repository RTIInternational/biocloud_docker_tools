	n_fail <- sum(!pass_vec, na.rm = TRUE)
	data.frame(
		metric = td$metric,
		rule = td$rule,
		n_pass = n_pass,
		n_fail = n_fail,
		total_samples = nrow(rnaseq_pheno_qc),
		stringsAsFactors = FALSE
	)
})
