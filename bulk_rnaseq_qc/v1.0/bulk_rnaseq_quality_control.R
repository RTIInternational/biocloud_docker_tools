		rule = "Shannon index > IQR cutoff OR transcriptome mapping percentage > 50%",
		pass = pass_shannon_or_transcriptome
	),
	list(
		metric = "mitochondrial_mapping_pct_lt50",
		rule = "Mitochondrial mapping percentage < 50%",
		pass = pass_mito
	),
	list(
		metric = "ribosomal_rna_mapping_pct_lt1",
		rule = "Ribosomal RNA mapping percentage < 1%",
		pass = pass_ribo
	)
