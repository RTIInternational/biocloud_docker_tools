pass_retained_reads <- !is.na(retained_reads_pct) & retained_reads_pct > 60
pass_mean_gc <- !is.na(mean_read_gc_pct) & mean_read_gc_pct >= 35 & mean_read_gc_pct <= 65
pass_salmon_mapping <- !is.na(salmon_mapping_pct) & salmon_mapping_pct > 30
pass_gene_mapping <- !is.na(gene_mapping_pct) & gene_mapping_pct > 80
pass_intergenic_genic_ratio <- !is.na(intergenic_genic_ratio) & intergenic_genic_ratio < 0.9
