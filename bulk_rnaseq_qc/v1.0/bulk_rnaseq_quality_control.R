# Bulk RNA-seq QC pipeline: load inputs, compute sample metrics, generate plots,
# apply QC thresholds, and write HTML/Markdown summaries.
pacman::p_load(
	logr, dplyr, tibble, stringr, DESeq2, tximport, patchwork, ggplot2,
	SummarizedExperiment
)

source("bulk_rnaseq_qc_functions.R")

args <- commandArgs(TRUE)

usage <- paste(
	"Usage: Rscript bulk_rnaseq_quality_control.R",
	"--multiqc_dir <path>",
	"--txi_rds <path>",
	"--pheno_tsv <path>",
	"--annotation_gtf <path>",
	"--sample_id_col <colname>",
	"--run_name <name>",
	"[--output_dir <path>]",
	"[--rin_col <colname>]",
	"[--sex_col <colname>]",
	"[--group_vars <comma-separated-colnames>]"
)

if (length(args) < 12) {
	stop(usage)
}

# Validate required CLI flags before any file or object loading.
flag_args <- parse_flag_args(args)
required_flags <- c("multiqc_dir", "txi_rds", "pheno_tsv", "annotation_gtf", "sample_id_col", "run_name")
missing_flags <- required_flags[!required_flags %in% names(flag_args)]
if (length(missing_flags) > 0) {
	stop(paste0("Missing required flags: ", paste(missing_flags, collapse = ", "), "\n", usage))
}

# Directory generated by MultiQC parser inputs.
multiqc_dir <- flag_args$multiqc_dir
# tximport object (.rds) containing counts/abundance/length.
txi_rds <- flag_args$txi_rds
# Phenotype table.
pheno_tsv <- flag_args$pheno_tsv
# GTF annotation file used for mito/ribo/chrY-derived metrics.
annotation_gtf <- flag_args$annotation_gtf
# Run identifier used in outputs and logs.
run_name <- flag_args$run_name
# Optional parent output directory. Defaults to outputs.
output_dir <- if ("output_dir" %in% names(flag_args)) {
	flag_args$output_dir
} else {
	"outputs"
}
# Required phenotype ID column.
sample_id_col <- flag_args$sample_id_col
# Optional RIN column name in phenotype table.
rin_col <- if ("rin_col" %in% names(flag_args)) flag_args$rin_col else "RIN"
# Optional sex column name for sex-stratified QC metrics.
sex_col <- if ("sex_col" %in% names(flag_args)) flag_args$sex_col else "Sex"
# Optional comma-separated list of phenotype columns for PCA grouping.
group_vars_arg <- if ("group_vars" %in% names(flag_args)) {
	flag_args$group_vars
} else {
	NULL
}
group_vars <- if (is.null(group_vars_arg)) {
	character(0)
} else {
	trimws(strsplit(group_vars_arg, ",", fixed = TRUE)[[1]])
}
group_vars <- group_vars[nzchar(group_vars)]

# Create a run-scoped output tree and central log file.
out_dir <- file.path(output_dir, paste0(run_name, "_quality_control"))
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
plot_dir <- file.path(out_dir, "plots")
dir.create(plot_dir, recursive = TRUE, showWarnings = FALSE)
table_dir <- file.path(out_dir, "tables")
dir.create(table_dir, recursive = TRUE, showWarnings = FALSE)

log_file <- file.path(out_dir, "bulk_rnaseq_qc.log")
lf <- logr::log_open(
	log_file, logdir = FALSE, show_notes = FALSE, traceback = FALSE
)
on.exit(logr::log_close())

logr::sep("Input parameters")
logr::log_print(paste("MultiQC dir:", multiqc_dir), console = FALSE)
logr::log_print(paste("txi RDS:", txi_rds), console = FALSE)
logr::log_print(paste("Phenotype TSV:", pheno_tsv), console = FALSE)
logr::log_print(paste("Annotation GTF:", annotation_gtf), console = FALSE)
logr::log_print(paste("Run name:", run_name), console = FALSE)
logr::log_print(paste("Output directory:", out_dir), console = FALSE)
logr::log_print(paste("Sample ID column:", sample_id_col), console = FALSE)
logr::log_print(paste("RIN column:", rin_col), console = FALSE)
logr::log_print(paste("Sex column:", sex_col), console = FALSE)
if (length(group_vars) > 0) {
	logr::log_print(
		paste("PCA group vars:", paste(group_vars, collapse = ", ")),
		console = FALSE
	)
} else {
	logr::log_print("PCA group vars: not provided; PCA plotting will be skipped.", console = FALSE)
}

required_paths <- c(multiqc_dir, txi_rds, pheno_tsv, annotation_gtf)
missing_paths <- required_paths[!file.exists(required_paths)]
if (length(missing_paths) > 0) {
	stop(
		paste0(
			"Missing required input path(s): ",
			paste(missing_paths, collapse = ", ")
		)
	)
}

logr::sep("Load QC and expression inputs")

# Load MultiQC-derived data and normalize expected nested structures.
qc_data <- load_paired_end_qc_data(data_dir = multiqc_dir)
logr::log_print("Loaded multiqc-derived qc_data object.", console = FALSE)

for (nm in c(
	"seq_duplication", "phred_bp", "phred_seq", "adapter_content",
	"gc_content", "fastqc"
)) {
	if (nm %in% names(qc_data)) {
		qc_data[[nm]] <- split_by_trim_status(qc_data[[nm]])
	}
}

fastqc_pre_subset <- if (
	"fastqc" %in% names(qc_data) &&
	is.list(qc_data$fastqc)
) {
	qc_data$fastqc
} else {
	NULL
}

txi <- readRDS(txi_rds)
if (!is.list(txi) || !"counts" %in% names(txi)) {
	stop("Input txi_rds must be an RDS containing a tximport-like list with counts.")
}

pheno_data <- read.table(pheno_tsv, sep = "\t", header = TRUE, check.names = FALSE)

# Optionally map a custom RIN column name to canonical RIN for downstream calls.
if (rin_col != "RIN" && rin_col %in% colnames(pheno_data)) {
	if ("RIN" %in% colnames(pheno_data)) {
		stop(
			paste0(
				"Both custom RIN column '", rin_col,
				"' and 'RIN' exist in phenotype table; refusing to overwrite existing 'RIN'."
			)
		)
	}
	colnames(pheno_data)[colnames(pheno_data) == rin_col] <- "RIN"
	group_vars[group_vars == rin_col] <- "RIN"
	rin_col <- "RIN"
}

# Enforce unique non-empty sample IDs before matching to tximport columns.
if (!sample_id_col %in% colnames(pheno_data)) {
	stop(
		paste0(
			"Sample ID column '", sample_id_col, "' not found in phenotype table."
		)
	)
}

sample_id_values <- as.character(pheno_data[[sample_id_col]])
if (any(is.na(sample_id_values) | sample_id_values == "")) {
	stop("Sample ID column contains missing or empty values.")
}
if (any(duplicated(sample_id_values))) {
	dup_vals <- unique(sample_id_values[duplicated(sample_id_values)])
	stop(
		paste0(
			"Sample ID column contains duplicate values; cannot set unique rownames. Duplicates include: ",
			paste(head(dup_vals, 10), collapse = ", ")
		)
	)
}
rownames(pheno_data) <- sample_id_values

shared_ids <- intersect(colnames(txi$counts), rownames(pheno_data))
if (length(shared_ids) == 0) {
	stop("No overlapping sample IDs between txi counts columns and phenotype rownames.")
}

txi <- subset_txi(txi = txi, ids = shared_ids, dimension = 2)
pheno_data <- pheno_data[shared_ids, , drop = FALSE]

dds <- DESeq2::DESeqDataSetFromTximport(txi, colData = pheno_data, design = ~1)
dds <- DESeq2::estimateSizeFactors(dds)
dds_vst <- DESeq2::vst(dds, blind = TRUE)
normalized_counts <- DESeq2::counts(dds, normalized = TRUE)

qc_ids <- rownames(pheno_data)

if (
	"fastqc" %in% names(qc_data) &&
	is.list(qc_data$fastqc) &&
	"trimmed_r1" %in% names(qc_data$fastqc)
) {
	pre_fastqc_ids <- extract_fastq_id(rownames(qc_data$fastqc$trimmed_r1))
	logr::log_print(
		paste("Phenotype ID examples:", paste(head(qc_ids, 6), collapse = ", ")),
		console = FALSE
	)
	logr::log_print(
		paste(
			"FastQC ID examples:",
			paste(head(pre_fastqc_ids, 6), collapse = ", ")
		),
		console = FALSE
	)
	logr::log_print(
		paste(
			"FastQC trimmed R1 overlap with phenotype IDs before subsetting:",
			length(intersect(pre_fastqc_ids, qc_ids))
		),
		console = FALSE
	)
	logr::log_print(
		paste(
			"FastQC overlap after normalized ID mapping:",
			length(intersect(normalize_sample_id(pre_fastqc_ids), normalize_sample_id(qc_ids)))
		),
		console = FALSE
	)
	logr::log_print(
		paste(
			"FastQC overlap after compact ID mapping:",
			length(intersect(normalize_sample_id_compact(pre_fastqc_ids), normalize_sample_id_compact(qc_ids)))
		),
		console = FALSE
	)
}

for (nm in names(qc_data)) {
	qc_data[[nm]] <- subset_qc_object(qc_data[[nm]], ids = qc_ids)
}

trimmed_r1_n <- if (
	"fastqc" %in% names(qc_data) &&
	"trimmed_r1" %in% names(qc_data$fastqc)
) {
	nrow(qc_data$fastqc$trimmed_r1)
} else {
	0L
}

trimmed_r2_n <- if (
	"fastqc" %in% names(qc_data) &&
	"trimmed_r2" %in% names(qc_data$fastqc)
) {
	nrow(qc_data$fastqc$trimmed_r2)
} else {
	0L
}

logr::log_print(
	paste("FastQC trimmed R1 rows after subsetting:", trimmed_r1_n),
	console = FALSE
)
logr::log_print(
	paste("FastQC trimmed R2 rows after subsetting:", trimmed_r2_n),
	console = FALSE
)

# FastQC recovery path: try generic subset, then FastQC-specific matching, then raw fallback.
if (
	(trimmed_r1_n == 0 || trimmed_r2_n == 0) &&
	!is.null(fastqc_pre_subset) &&
	"trimmed_r1" %in% names(fastqc_pre_subset) &&
	"trimmed_r2" %in% names(fastqc_pre_subset)
) {
	logr::log_print(
		"FastQC trimmed data were empty after generic subsetting; trying FastQC-specific recovery using Sample labels.",
		console = FALSE
	)
	qc_data$fastqc$trimmed_r1 <- recover_fastqc_subset(fastqc_pre_subset$trimmed_r1, qc_ids)
	qc_data$fastqc$trimmed_r2 <- recover_fastqc_subset(fastqc_pre_subset$trimmed_r2, qc_ids)
	trimmed_r1_n <- nrow(qc_data$fastqc$trimmed_r1)
	trimmed_r2_n <- nrow(qc_data$fastqc$trimmed_r2)
	logr::log_print(
		paste("FastQC trimmed R1 rows after recovery:", trimmed_r1_n),
		console = FALSE
	)
	logr::log_print(
		paste("FastQC trimmed R2 rows after recovery:", trimmed_r2_n),
		console = FALSE
	)
}

if (trimmed_r1_n == 0 || trimmed_r2_n == 0) {
	logr::log_print(
		"FastQC trimmed data still empty; reloading raw FastQC from MultiQC and using raw parsed trimmed R1/R2 for plotting.",
		console = FALSE
	)
	raw_qc <- load_paired_end_qc_data(data_dir = multiqc_dir)
	if ("fastqc" %in% names(raw_qc)) {
		fastqc_df <- raw_qc$fastqc
		sample_labels <- if ("Sample" %in% colnames(fastqc_df)) {
			as.character(fastqc_df$Sample)
		} else {
			rownames(fastqc_df)
		}
		sample_labels <- trimws(as.character(sample_labels))
		r1_mask <- grepl("\\.trimmed\\.R1$", sample_labels)
		r2_mask <- grepl("\\.trimmed\\.R2$", sample_labels)
		raw_r1 <- fastqc_df[r1_mask, , drop = FALSE]
		raw_r2 <- fastqc_df[r2_mask, , drop = FALSE]
		if (nrow(raw_r1) > 0) {
			rownames(raw_r1) <- make.unique(extract_fastq_id(sample_labels[r1_mask]))
		}
		if (nrow(raw_r2) > 0) {
			rownames(raw_r2) <- make.unique(extract_fastq_id(sample_labels[r2_mask]))
		}

		qc_data$fastqc$trimmed_r1 <- recover_fastqc_subset(raw_r1, qc_ids)
		qc_data$fastqc$trimmed_r2 <- recover_fastqc_subset(raw_r2, qc_ids)

		if (nrow(qc_data$fastqc$trimmed_r1) == 0 && nrow(raw_r1) > 0) {
			qc_data$fastqc$trimmed_r1 <- raw_r1
		}
		if (nrow(qc_data$fastqc$trimmed_r2) == 0 && nrow(raw_r2) > 0) {
			qc_data$fastqc$trimmed_r2 <- raw_r2
		}

		trimmed_r1_n <- nrow(qc_data$fastqc$trimmed_r1)
		trimmed_r2_n <- nrow(qc_data$fastqc$trimmed_r2)
		logr::log_print(
			paste("FastQC trimmed R1 rows after second recovery:", trimmed_r1_n),
			console = FALSE
		)
		logr::log_print(
			paste("FastQC trimmed R2 rows after second recovery:", trimmed_r2_n),
			console = FALSE
		)
	}
}

if (trimmed_r1_n == 0 || trimmed_r2_n == 0) {
	logr::log_print(
		"FastQC trimmed R1/R2 data are still empty; FastQC paired trimmed plots will be skipped.",
		console = FALSE
	)
}

logr::log_print(
	paste("Samples retained for QC:", length(qc_ids)),
	console = FALSE
)

if ("trimmomatic_dropped_pct" %in% group_vars) {
	trimmomatic_dropped_for_pca <- collect_metric({
		td <- qc_data$trimmomatic
		td <- td[qc_ids, , drop = FALSE]
		as_numeric <- suppressWarnings(as.numeric(td[, "dropped_pct"]))
		data.frame(trimmomatic_dropped_pct = as_numeric, row.names = qc_ids)
	}, "trimmomatic_dropped_pct_for_pca")
	if (!is.null(trimmomatic_dropped_for_pca)) {
		pheno_data$trimmomatic_dropped_pct <- trimmomatic_dropped_for_pca[rownames(pheno_data), 1]
		SummarizedExperiment::colData(dds)$trimmomatic_dropped_pct <- pheno_data$trimmomatic_dropped_pct
		SummarizedExperiment::colData(dds_vst)$trimmomatic_dropped_pct <- pheno_data$trimmomatic_dropped_pct
		logr::log_print(
			"Added trimmomatic_dropped_pct to phenotype data for PCA grouping.",
			console = FALSE
		)
	}
}

logr::sep("Plot QC summaries")

# Build plotting inputs from parsed FastQC data, with deterministic raw fallback.
fastqc_plot_data <- NULL
fastqc_plot_data <- tryCatch(
	{
		raw_fastqc <- load_paired_end_qc_data(data_dir = multiqc_dir)$fastqc
		parsed_fastqc <- parse_by_trim_status(
			raw_fastqc,
			paired_end = TRUE,
			r1_query = "(\\.R1|_R1)",
			r2_query = "(\\.R2|_R2)"
		)
		list(
			trimmed_r1 = parsed_fastqc$trimmed_r1,
			trimmed_r2 = parsed_fastqc$trimmed_r2
		)
	},
	error = function(e) {
		logr::log_print(
			paste0("Failed to build direct FastQC plotting data: ", e$message),
			console = FALSE
		)
		NULL
	}
)

fastqc_trimmed_r1_for_plot <- data.frame()
fastqc_trimmed_r2_for_plot <- data.frame()

if (
	!is.null(fastqc_plot_data) &&
	"trimmed_r1" %in% names(fastqc_plot_data) &&
	"trimmed_r2" %in% names(fastqc_plot_data) &&
	is.data.frame(fastqc_plot_data$trimmed_r1) &&
	is.data.frame(fastqc_plot_data$trimmed_r2)
) {
	fastqc_trimmed_r1_for_plot <- fastqc_plot_data$trimmed_r1
	fastqc_trimmed_r2_for_plot <- fastqc_plot_data$trimmed_r2
}

# Deterministic fallback: extract paired trimmed rows directly from raw fastqc.
if (nrow(fastqc_trimmed_r1_for_plot) == 0 || nrow(fastqc_trimmed_r2_for_plot) == 0) {
	logr::log_print(
		"Direct parse returned empty FastQC trimmed tables for plotting; applying raw suffix-based fallback.",
		console = FALSE
	)
	raw_fastqc_df <- load_paired_end_qc_data(data_dir = multiqc_dir)$fastqc
	raw_labels <- if ("Sample" %in% colnames(raw_fastqc_df)) {
		as.character(raw_fastqc_df$Sample)
	} else {
		rownames(raw_fastqc_df)
	}
	raw_labels <- trimws(as.character(raw_labels))
	r1_mask <- grepl("\\.trimmed\\.R1$", raw_labels)
	r2_mask <- grepl("\\.trimmed\\.R2$", raw_labels)
	fastqc_trimmed_r1_for_plot <- raw_fastqc_df[r1_mask, , drop = FALSE]
	fastqc_trimmed_r2_for_plot <- raw_fastqc_df[r2_mask, , drop = FALSE]
}

logr::log_print(
	paste("FastQC paired plot rows (R1):", nrow(fastqc_trimmed_r1_for_plot)),
	console = FALSE
)
logr::log_print(
	paste("FastQC paired plot rows (R2):", nrow(fastqc_trimmed_r2_for_plot)),
	console = FALSE
)

with_plot_guard({
	p3 <- plot_seq_depth(fastqc_trimmed_r1_for_plot, sort = TRUE) +
		ggplot2::ggtitle("Post-Trimmomatic paired R1 reads")
	p4 <- plot_seq_depth(fastqc_trimmed_r2_for_plot, sort = TRUE) +
		ggplot2::ggtitle("Post-Trimmomatic paired R2 reads")
	h3 <- plot_seq_depth_hist(fastqc_trimmed_r1_for_plot) +
		ggplot2::ggtitle("Post-Trimmomatic paired R1 reads")
	h4 <- plot_seq_depth_hist(fastqc_trimmed_r2_for_plot) +
		ggplot2::ggtitle("Post-Trimmomatic paired R2 reads")
	save_plot((p3 + h3) / (p4 + h4), "fastqc_seq_depth_posttrimmomatic_paired.png", 12.5, 8)
}, "seq depth")

with_plot_guard({
	p3 <- plot_unique_read_pct(
		fastqc_trimmed_r1_for_plot, sort = TRUE, fill = "red4"
	) + ggplot2::ggtitle("Post-Trimmomatic paired R1 reads")
	p4 <- plot_unique_read_pct(
		fastqc_trimmed_r2_for_plot, sort = TRUE, fill = "red4"
	) + ggplot2::ggtitle("Post-Trimmomatic paired R2 reads")
	save_plot(p3 + p4, "fastqc_unique_pct_posttrimmomatic_paired.png", 12.5, 4.5)
}, "unique read percent")

with_plot_guard({
	p <- plot_phred_per_bp(
		qc_data$phred_bp[c("trimmed_r1", "trimmed_r2")],
		labels = c("R1", "R2"),
		line_colors = c("goldenrod2", "steelblue4"),
		alpha = 0.5
	) + ggplot2::ggtitle("Post-Trimmomatic paired reads")
	save_plot(p, "fastqc_phred_bp_posttrimmomatic_paired.png", 9, 4)
}, "phred per bp")

with_plot_guard({
	p <- plot_gc_content(
		qc_data$gc_content[c("trimmed_r1", "trimmed_r2")],
		labels = c("R1", "R2"),
		line_colors = c("goldenrod2", "steelblue4"),
		alpha = 0.5
	) + ggplot2::ggtitle("Post-Trimmomatic paired reads")
	save_plot(p, "fastqc_gc_content_posttrimmomatic_paired.png", 7, 4)
}, "gc content")

with_plot_guard({
	p_trim <- plot_trimmomatic_paired(
		data = qc_data$trimmomatic,
		binsize = c(2.5, 0.25)
	)
	save_plot(p_trim$excluded + p_trim$retained, "trimmomatic_stats.png", 9, 4)
}, "trimmomatic")

with_plot_guard({
	p <- plot_salmon_stats(qc_data$salmon)
	save_plot(p, "salmon_input_vs_mapped.png", 5, 4)
}, "salmon scatter")

with_plot_guard({
	p <- plot_hisat2_stats(qc_data$hisat2)
	save_plot(p, "hisat2_mapping_stats.png", 6, 5)
}, "hisat2 scatter")

with_plot_guard({
	p <- plot_hisat2_vs_salmon(qc_data$hisat2, qc_data$salmon)
	save_plot(p, "salmon_vs_hisat2_mapping_rate.png", 5, 5)
}, "salmon vs hisat2")

with_plot_guard({
	p <- plot_mapping_categories(
		qc_data$rseqc_alignment_category,
		sort = TRUE,
		consolidate = TRUE
	)
	save_plot(p, "rseqc_read_distribution_consolidated.png", 14, 7)
}, "mapping categories")

with_plot_guard({
	if (rin_col %in% colnames(pheno_data)) {
		p <- plot_rin(
			data = pheno_data[, rin_col, drop = FALSE],
			return_data = FALSE,
			colors = "gray30",
			box_fill = "goldenrod",
			jitter_alpha = 0.5
		)
		save_plot(p$hist / p$boxplot, "rin.png", 6, 6)
	} else {
		logr::log_print(
			paste0("RIN column '", rin_col, "' not found. Skipping RIN plot."),
			console = FALSE
		)
	}
}, "rin")

logr::log_print("Starting streamed annotation ID extraction.", console = FALSE)
mitochondrial_ids <- get_annotation_gene_ids(annotation_gtf, seqnames = c("chrM", "MT", "M"))
ribo_ids <- get_annotation_gene_ids(annotation_gtf, gene_types = c("rRNA"))
logr::log_print(
	paste0(
		"Resolved feature IDs - mitochondrial: ", length(mitochondrial_ids),
		"; ribosomal: ", length(ribo_ids)
	),
	console = FALSE
)

mitochondrial_mapping_rate <- collect_metric({
	out <- compute_feature_fraction(normalized_counts, mitochondrial_ids)
	out <- out[qc_ids, "values", drop = FALSE]
	colnames(out) <- "mitochondrial_mapping_rate"
	out
}, "mitochondrial_mapping_rate")
logr::log_print("Computed mitochondrial mapping rate.", console = FALSE)

ribo_rna_mapping_rate <- collect_metric({
	out <- compute_feature_fraction(normalized_counts, ribo_ids)
	out <- out[qc_ids, "values", drop = FALSE]
	colnames(out) <- "ribo_rna_mapping_rate"
	out
}, "ribo_rna_mapping_rate")
logr::log_print("Computed ribosomal RNA mapping rate.", console = FALSE)

with_plot_guard({
	p <- plot_fraction_summary(
		mitochondrial_mapping_rate,
		"Mitochondrial RNA"
	)
	save_plot(p$hist / p$boxplot, "mitochondrial_mapping_rate.png", 6, 6)
}, "mitochondrial")
logr::log_print("Completed mitochondrial plot block.", console = FALSE)

if (!is.null(mitochondrial_mapping_rate)) {
	pheno_data$mitochondrial_mapping_rate <- mitochondrial_mapping_rate[rownames(pheno_data), 1]
	SummarizedExperiment::colData(dds)$mitochondrial_mapping_rate <- pheno_data$mitochondrial_mapping_rate
	SummarizedExperiment::colData(dds_vst)$mitochondrial_mapping_rate <- pheno_data$mitochondrial_mapping_rate
}

with_plot_guard({
	p <- plot_fraction_summary(
		ribo_rna_mapping_rate,
		"Ribosomal RNA"
	)
	save_plot(p$hist / p$boxplot, "ribosomal_rna_mapping_rate.png", 6, 6)
}, "ribosomal")
logr::log_print("Completed ribosomal plot block.", console = FALSE)

with_plot_guard({
	p <- plot_shannon_index(
		data = DESeq2::counts(dds, normalized = TRUE),
		min_value = 10,
		colors = "gray30"
	)
	save_plot(p$hist / p$boxplot, "shannon_diversity.png", 6, 6)
}, "shannon")

with_plot_guard({
	if (sex_col %in% colnames(pheno_data)) {
		chr_y_ids <- get_annotation_gene_ids(
			annotation_gtf,
			seqnames = c("chrY", "Y"),
			exclude_par = TRUE
		)
		chr_y_ids <- intersect(chr_y_ids, rownames(normalized_counts))

		if (length(chr_y_ids) == 0) {
			logr::log_print(
