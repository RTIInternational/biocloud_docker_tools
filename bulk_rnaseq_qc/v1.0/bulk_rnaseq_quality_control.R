			as.character(fastqc_df$Sample)
		} else {
			rownames(fastqc_df)
		}
		sample_labels <- trimws(as.character(sample_labels))
		r1_mask <- grepl("\\\\.trimmed\\\\.R1$", sample_labels)
		r2_mask <- grepl("\\\\.trimmed\\\\.R2$", sample_labels)
		raw_r1 <- fastqc_df[r1_mask, , drop = FALSE]
		raw_r2 <- fastqc_df[r2_mask, , drop = FALSE]
		if (nrow(raw_r1) > 0) {
			rownames(raw_r1) <- extract_fastq_id(sample_labels[r1_mask])
		}
		if (nrow(raw_r2) > 0) {
			rownames(raw_r2) <- extract_fastq_id(sample_labels[r2_mask])
		}

		qc_data$fastqc$trimmed_r1 <- recover_fastqc_subset(raw_r1, qc_ids)
		qc_data$fastqc$trimmed_r2 <- recover_fastqc_subset(raw_r2, qc_ids)

		if (nrow(qc_data$fastqc$trimmed_r1) == 0 && nrow(raw_r1) > 0) {
			qc_data$fastqc$trimmed_r1 <- raw_r1
		}
		if (nrow(qc_data$fastqc$trimmed_r2) == 0 && nrow(raw_r2) > 0) {
			qc_data$fastqc$trimmed_r2 <- raw_r2
		}

		trimmed_r1_n <- nrow(qc_data$fastqc$trimmed_r1)
		trimmed_r2_n <- nrow(qc_data$fastqc$trimmed_r2)
		logr::log_print(
			paste("FastQC trimmed R1 rows after second recovery:", trimmed_r1_n),
			console = FALSE
		)
		logr::log_print(
			paste("FastQC trimmed R2 rows after second recovery:", trimmed_r2_n),
			console = FALSE
		)
	}
}

