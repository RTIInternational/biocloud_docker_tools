summary_rows <- lapply(threshold_defs, function(td) {
	pass_vec <- td$pass
	n_pass <- sum(pass_vec, na.rm = TRUE)
	n_fail <- sum(!pass_vec, na.rm = TRUE)
	data.frame(
		metric = td$metric,
		rule = td$rule,
		n_pass = n_pass,
		n_fail = n_fail,
		total_samples = nrow(rnaseq_pheno_qc),
		stringsAsFactors = FALSE
	)
})
