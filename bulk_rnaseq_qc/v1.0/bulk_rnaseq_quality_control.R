	data.frame(
		metric = td$metric,
		rule = td$rule,
		n_failed = length(fail_ids),
		failed_samples = if (length(fail_ids) == 0) "None" else paste(fail_ids, collapse = ", "),
		stringsAsFactors = FALSE
	)
})
